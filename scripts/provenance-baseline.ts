// Zero-shot provenance baseline: Jev reads each article of the Russell et al. (2025)
// human_detectors dataset with the paper's own zero-shot detector prompt, verbatim
// (prompts/detector_prompts/classify_zero_shot.txt, MIT). Articles never enter the repo.
import { appendFile, mkdir, readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { APIError, choice } from "@typesafe-ai/sdk";
import type { Questions } from "@typesafe-ai/sdk";
import { createJevClient, INPUT_USD_PER_MILLION, MODEL, validateResponse } from "../src/jev.js";
import { invariant, object, ValidationError } from "../src/registry.js";

const INSTRUCTIONS =
  "You are given a candidate text. Your task is to carefully read the candidate text and determine whether it was either written by a human or generated by AI.\n\nIs the above candidate text HUMAN-WRITTEN or AI-GENERATED?";
const CRITERIA = {
  "HUMAN-WRITTEN": "Answer HUMAN-WRITTEN if the candidate text was likely written by a human.",
  "AI-GENERATED": "Answer AI-GENERATED if the candidate text was likely generated by an AI.",
} as const;
const ORDERS = {
  original: { provenance: choice(INSTRUCTIONS, CRITERIA) },
  reversed: {
    provenance: choice(INSTRUCTIONS, {
      "AI-GENERATED": CRITERIA["AI-GENERATED"],
      "HUMAN-WRITTEN": CRITERIA["HUMAN-WRITTEN"],
    }),
  },
} satisfies Record<string, Questions>;

interface Article {
  id: string;
  condition: string;
  truth: "ai" | "human";
  text: string;
  experts: number; // expert votes for AI
}
interface Row {
  id: string;
  condition: string;
  truth: Article["truth"];
  experts: number;
  variant: keyof typeof ORDERS;
  p_ai: number | null;
  input_tokens: number;
  error: string | null;
}

function readArticles(raw: unknown): Article[] {
  return Object.entries(object(raw, "Dataset")).map(([id, value]) => {
    const entry = object(value, `Article ${id}`);
    const { article, generation_model, ground_truth } = entry;
    invariant(
      typeof article === "string" &&
        typeof generation_model === "string" &&
        (ground_truth === "AI-generated" || ground_truth === "Human-written"),
      `Unexpected article shape: ${id}`,
    );
    let experts = 0;
    for (let i = 1; i <= 5; i += 1) {
      const vote = entry[`annotator_${i}`];
      if (vote && typeof vote === "object" && "guess" in vote && vote.guess === "Machine-Generated")
        experts += 1;
    }
    return {
      id,
      condition: generation_model,
      truth: ground_truth === "AI-generated" ? "ai" : "human",
      text: article,
      experts,
    };
  });
}

function auroc(scores: { score: number; positive: boolean }[]): number {
  const pos = scores.filter((s) => s.positive);
  const neg = scores.filter((s) => !s.positive);
  let wins = 0;
  for (const p of pos)
    for (const n of neg) wins += p.score > n.score ? 1 : p.score === n.score ? 0.5 : 0;
  return wins / (pos.length * neg.length);
}

try {
  const [datasetPath, outArg] = process.argv.slice(2);
  invariant(
    datasetPath && outArg,
    "Usage: npm run provenance-baseline -- human_detectors.json NEW_OUT_DIR",
  );
  const out = resolve(outArg);
  await mkdir(out, { recursive: false, mode: 0o700 });
  const articles = readArticles(JSON.parse(await readFile(datasetPath, "utf8")) as unknown);
  const jobs = articles.flatMap((article) =>
    (["original", "reversed"] as const).map((variant) => ({ article, variant })),
  );
  const client = createJevClient();
  const rows: Row[] = [];
  let next = 0;
  async function worker(): Promise<void> {
    while (next < jobs.length) {
      const job = jobs[next++];
      invariant(job, "Missing job");
      const questions = ORDERS[job.variant];
      const row: Row = {
        id: job.article.id,
        condition: job.article.condition,
        truth: job.article.truth,
        experts: job.article.experts,
        variant: job.variant,
        p_ai: null,
        input_tokens: 0,
        error: null,
      };
      try {
        const response = await client.systemOne(
          { model: MODEL, state: job.article.text, questions },
          { signal: AbortSignal.timeout(60_000) },
        );
        validateResponse(response, questions);
        row.p_ai = response.answers.provenance.probabilities["AI-GENERATED"];
        row.input_tokens = response.usage.input_tokens;
      } catch (cause: unknown) {
        // Raw SDK errors may contain service bodies; keep only the class and status.
        row.error =
          cause instanceof APIError
            ? `api ${cause.status}`
            : cause instanceof ValidationError
              ? "validation"
              : "transport";
      }
      rows.push(row);
      await appendFile(join(out, "rows.jsonl"), JSON.stringify(row) + "\n");
    }
  }
  await Promise.all(Array.from({ length: 8 }, worker));

  const byArticle = new Map<string, { article: Article; p: number[] }>();
  for (const article of articles) byArticle.set(article.id, { article, p: [] });
  for (const row of rows) if (row.p_ai !== null) byArticle.get(row.id)?.p.push(row.p_ai);
  const scored = [...byArticle.values()]
    .filter((entry) => entry.p.length === 2)
    .map(({ article, p }) => ({
      ...article,
      p_ai: (p[0]! + p[1]!) / 2,
      flip: Math.abs(p[0]! - p[1]!),
    }));
  const lines = [
    `# Jev zero-shot provenance on Russell et al. human_detectors`,
    ``,
    `Model ${MODEL}; paper's zero-shot detector prompt verbatim; both label orders averaged; AI if mean P(AI) > 0.5.`,
    `Scored ${scored.length}/${articles.length} articles; ${rows.filter((r) => r.error).length} failed requests.`,
    ``,
    `| Condition | TPR (AI caught) | FPR (human called AI) | AUROC | mean P(AI) AI / human | expert majority acc |`,
    `| --- | ---: | ---: | ---: | ---: | ---: |`,
  ];
  const conditions = [...new Set(scored.map((s) => s.condition))].sort();
  for (const condition of [...conditions, "ALL"]) {
    const set = scored.filter((s) => condition === "ALL" || s.condition === condition);
    const ai = set.filter((s) => s.truth === "ai");
    const human = set.filter((s) => s.truth === "human");
    const rate = (xs: typeof set) => xs.filter((s) => s.p_ai > 0.5).length / xs.length;
    const mean = (xs: typeof set) => xs.reduce((sum, s) => sum + s.p_ai, 0) / xs.length;
    const expertAcc = set.filter((s) => s.experts >= 3 === (s.truth === "ai")).length / set.length;
    lines.push(
      `| ${condition} | ${(100 * rate(ai)).toFixed(1)}% | ${(100 * rate(human)).toFixed(1)}% | ${auroc(set.map((s) => ({ score: s.p_ai, positive: s.truth === "ai" }))).toFixed(3)} | ${mean(ai).toFixed(3)} / ${mean(human).toFixed(3)} | ${(100 * expertAcc).toFixed(1)}% |`,
    );
  }
  const tokens = rows.reduce((sum, r) => sum + r.input_tokens, 0);
  lines.push(
    ``,
    `Mean |P(AI) original − reversed|: ${(scored.reduce((s, x) => s + x.flip, 0) / scored.length).toFixed(3)}.`,
    `Input tokens ${tokens}; estimated Jev cost USD ${((tokens / 1e6) * INPUT_USD_PER_MILLION).toFixed(4)}.`,
  );
  await writeFile(join(out, "summary.md"), lines.join("\n") + "\n");
  await writeFile(
    join(out, "scored.json"),
    JSON.stringify(
      scored.map(({ text: _text, ...rest }) => rest),
      null,
      2,
    ) + "\n",
  );
  console.log(lines.join("\n"));
} catch (error: unknown) {
  console.error(
    error instanceof ValidationError
      ? error.message
      : "Provenance baseline failed; check the dataset path, API key and that the output directory is new.",
  );
  process.exitCode = 2;
}
